// Generates sim/src/trig.rs: a baked integer sine table (plan 6.6 "Aim"). Run once and commit the output:
//   node tools/gen-trig.ts > sim/src/trig.rs
// The sim never computes trig at runtime (invariant 3); floats are fine here because this script is the
// only place they appear and its output is checked in.
const N = 1024; // entries per full turn; an aim angle (u16, 65536 per turn) indexes with `angle >> 6`
const ONE = 16384; // Q14: 16384 is 1.0
const rows: number[] = [];
for (let i = 0; i < N; i++) rows.push(Math.round(Math.sin((2 * Math.PI * i) / N) * ONE));
let out = `//! GENERATED by tools/gen-trig.ts, do not edit. Integer sine for aim angles (plan 6.6).
//! \`SIN[i]\` is sin(2*pi*i/${N}) in Q14. Cosine is \`SIN[(i + ${N / 4}) % ${N}]\`. Angle 0 points along +x and the
//! angle grows towards +y (down the screen), the same turn direction as \`atan2(dy, dx)\` with y down.

pub const TRIG_ENTRIES: usize = ${N};
pub const TRIG_ONE: i32 = ${ONE};
pub const SIN: [i16; ${N}] = [\n`;
for (let i = 0; i < N; i += 16) out += "    " + rows.slice(i, i + 16).join(", ") + ",\n";
out += `];

/// (cos, sin) of an aim angle (65536 units per turn), Q14.
pub fn dir(angle: u16) -> (i32, i32) {
    let i = usize::from(angle >> 6);
    (i32::from(SIN[(i + TRIG_ENTRIES / 4) % TRIG_ENTRIES]), i32::from(SIN[i]))
}
`;
process.stdout.write(out);
